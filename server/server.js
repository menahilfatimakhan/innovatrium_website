/* ==========================================================================
   Innovatrium CMS — tiny backend
   --------------------------------------------------------------------------
   Serves the static site AND a small password-protected admin API that edits
   form links, deadlines, and application status.

   Data flow:
     data/content.json          <- canonical source of truth (this file writes it)
     assets/js/site-config.js   <- generated artifact the public pages read

   Only the admin ever hits this server. Visitors read the static site-config.js,
   so the public site keeps working even if this process is down.
   ========================================================================== */
'use strict';

const path = require('path');
const fs = require('fs');
const express = require('express');
const session = require('express-session');

require('dotenv').config({ path: path.join(__dirname, '.env') });

const ROOT = path.join(__dirname, '..');
const DATA_FILE = path.join(ROOT, 'data', 'content.json');
const CONFIG_FILE = path.join(ROOT, 'assets', 'js', 'site-config.js');

const ALLOWED_PAGES = ['incubation', 'cybersecurity', 'skilltoearn', 'ventureden'];

const app = express();
app.disable('x-powered-by');
app.use(express.json({ limit: '64kb' }));

app.use(session({
  name: 'innv.sid',
  secret: process.env.SESSION_SECRET || 'dev-only-insecure-secret',
  resave: false,
  saveUninitialized: false,
  cookie: {
    httpOnly: true,
    sameSite: 'lax',
    maxAge: 1000 * 60 * 60 * 8,            // 8 hours
    secure: process.env.NODE_ENV === 'production'
  }
}));

/* --- Never expose server internals or raw data over HTTP ------------------ */
app.use((req, res, next) => {
  const p = req.path;
  if (p.startsWith('/server') || p.startsWith('/node_modules') || p.startsWith('/data')) {
    return res.status(404).send('Not found');
  }
  next();
});

/* --- Helpers -------------------------------------------------------------- */
function requireAuth(req, res, next) {
  if (req.session && req.session.authed) return next();
  return res.status(401).json({ error: 'Not signed in' });
}

function validate(d) {
  if (!d || typeof d !== 'object') return 'Invalid payload';
  const strFields = ['contactEmail', 'phone', 'address', 'whatsapp'];
  for (const f of strFields) {
    if (d[f] != null && typeof d[f] !== 'string') return `${f} must be text`;
  }
  if (d.socials && typeof d.socials !== 'object') return 'socials must be an object';
  if (!d.pages || typeof d.pages !== 'object') return 'Missing pages';
  for (const key of Object.keys(d.pages)) {
    if (!ALLOWED_PAGES.includes(key)) return `Unknown page: ${key}`;
    const p = d.pages[key];
    if (typeof p.formUrl !== 'string') return `${key}: form link must be text`;
    if (!['open', 'closed'].includes(p.status)) return `${key}: status must be "open" or "closed"`;
    if (p.deadline && !/^\d{4}-\d{2}-\d{2}$/.test(p.deadline)) return `${key}: deadline must be YYYY-MM-DD`;
  }
  return null;
}

function generateConfigJs(data) {
  return '/* ==========================================================================\n' +
         '   Innovatrium — Site Configuration (GENERATED by the CMS admin).\n' +
         '   Do not edit by hand; changes are overwritten on the next save.\n' +
         '   ========================================================================== */\n' +
         'window.SITE_CONFIG = ' + JSON.stringify(data, null, 2) + ';\n';
}

/* --- API ------------------------------------------------------------------ */
app.post('/api/login', (req, res) => {
  if (!process.env.ADMIN_PASSWORD) {
    return res.status(500).json({ error: 'Server has no ADMIN_PASSWORD configured' });
  }
  const { password } = req.body || {};
  if (password && password === process.env.ADMIN_PASSWORD) {
    req.session.authed = true;
    return res.json({ ok: true });
  }
  return res.status(401).json({ error: 'Incorrect password' });
});

app.post('/api/logout', (req, res) => {
  req.session.destroy(() => res.json({ ok: true }));
});

app.get('/api/session', (req, res) => {
  res.json({ authed: !!(req.session && req.session.authed) });
});

app.get('/api/content', requireAuth, (req, res) => {
  try {
    res.json(JSON.parse(fs.readFileSync(DATA_FILE, 'utf8')));
  } catch (e) {
    res.status(500).json({ error: 'Could not read content.json' });
  }
});

app.post('/api/content', requireAuth, (req, res) => {
  const data = req.body;
  const err = validate(data);
  if (err) return res.status(400).json({ error: err });
  try {
    fs.writeFileSync(DATA_FILE, JSON.stringify(data, null, 2) + '\n');
    fs.writeFileSync(CONFIG_FILE, generateConfigJs(data));
    res.json({ ok: true });
  } catch (e) {
    res.status(500).json({ error: 'Could not save: ' + e.message });
  }
});

/* --- Static site (served last so /api and guards win) --------------------- */
app.use(express.static(ROOT, { dotfiles: 'ignore', extensions: ['html'] }));

const PORT = process.env.PORT || 3000;
app.listen(PORT, () => {
  console.log(`Innovatrium CMS running on http://localhost:${PORT}`);
  console.log(`Admin editor: http://localhost:${PORT}/admin.html`);
  if (!process.env.ADMIN_PASSWORD) {
    console.warn('WARNING: ADMIN_PASSWORD is not set — the admin login will refuse all passwords.');
  }
});
